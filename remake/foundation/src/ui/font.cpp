uint32_t utf8Next(const char*& p) {
    const auto b = (uint8_t)*p;
    if (b < 0x80) {
        ++p;
        return b;
    }
    // 2-, 3- and 4-byte sequences with the minimal validity checks that keep a
    // truncated tail from running past the NUL: continuation bytes required,
    // overlongs and surrogates rejected. Anything rejected becomes U+FFFD.
    uint32_t cp = 0xFFFDu;
    size_t want = 0;
    if ((b & 0xE0) == 0xC0) {
        cp = b & 0x1F;
        want = 1;
    } else if ((b & 0xF0) == 0xE0) {
        cp = b & 0x0F;
        want = 2;
    } else if ((b & 0xF8) == 0xF0) {
        cp = b & 0x07;
        want = 3;
    } else {
        ++p;
        return cp;
    }
    for (size_t i = 0; i < want; ++i) {
        const auto c = (uint8_t)p[1 + i];
        if ((c & 0xC0) != 0x80) {
            p += 1 + i;
            return 0xFFFDu;
        }
        cp = (cp << 6) | (c & 0x3F);
    }
    p += 1 + want;
    return cp;
}

TextExtent measureText(const char* text, float scale) {
    TextExtent e;
    if (!text || !*text || scale <= 0.f) return e;
    int cells = 0, maxCells = 0, lines = 1;
    for (const char* p = text; *p;) {
        if (*p == '\n') {
            if (cells > maxCells) maxCells = cells;
            cells = 0;
            ++lines;
            ++p;
            continue;
        }
        if ((uint8_t)*p < 32) {
            ++p;   // other controls vanish without advancing, like D3DX
            continue;
        }
        utf8Next(p);   // every codepoint is one monospace cell, '?' included
        ++cells;
    }
    if (cells > maxCells) maxCells = cells;
    e.lines = lines;
    e.width = (float)maxCells * (float)kGlyphAdvance * scale;
    e.height = (float)lines * (float)kLineHeight * scale;
    return e;
}

namespace {

// Cell top-left in atlas pixels for a supported codepoint.
void cellOrigin(uint32_t cp, float& cx, float& cy) {
    const uint32_t idx = cp - 32;
    cx = (float)((idx % kAtlasCols) * kAtlasCell);
    cy = (float)((idx / kAtlasCols) * kAtlasCell);
}

}  // namespace

void layoutText(const char* text, float x, float y, float scale, std::vector<TextQuad>& out) {
    if (!text || !*text || scale <= 0.f) return;
    float cx = x, cy = y;
    for (const char* p = text; *p;) {
        if (*p == '\n') {
            cx = x;
            cy += (float)kLineHeight * scale;
            ++p;
            continue;
        }
        if ((uint8_t)*p < 32) {
            ++p;
            continue;
        }
        uint32_t cp = utf8Next(p);
        if (!glyphSupported(cp)) cp = '?';
        float ax = 0.f, ay = 0.f;
        cellOrigin(cp, ax, ay);
        TextQuad q;
        q.x = cx;
        q.y = cy;
        q.w = (float)kGlyphW * scale;
        q.h = (float)kGlyphH * scale;
        q.u0 = ax / (float)kAtlasW;
        q.v0 = ay / (float)kAtlasH;
        q.u1 = (ax + (float)kGlyphW) / (float)kAtlasW;
        q.v1 = (ay + (float)kGlyphH) / (float)kAtlasH;
        out.push_back(q);
        cx += (float)kGlyphAdvance * scale;
    }
}

void layoutTextCentered(const char* text, float centerX, float y, float scale,
                        std::vector<TextQuad>& out) {
    const TextExtent e = measureText(text, scale);
    layoutText(text, centerX - e.width * 0.5f, y, scale, out);
}

void buildAtlasRGBA(std::vector<uint8_t>& rgba, uint32_t& w, uint32_t& h) {
    w = kAtlasW;
    h = kAtlasH;
    rgba.assign((size_t)w * h * 4, 0);
    // White with coverage in alpha: the ui shader multiplies texel * tint, so
    // glyph colour comes entirely from the tint and one atlas serves all of it.
    for (uint32_t g = 0; g < 95; ++g) {
        const uint32_t col = g % kAtlasCols, row = g / kAtlasCols;
        for (int r = 0; r < kGlyphH; ++r) {
            const uint8_t bits = kFontGlyphs[g][r];
            for (int c = 0; c < kGlyphW; ++c) {
                if (!(bits & (uint8_t)(0x10u >> c))) continue;
                const uint32_t px = col * kAtlasCell + (uint32_t)c;
                const uint32_t py = row * kAtlasCell + (uint32_t)r;
                uint8_t* dst = rgba.data() + ((size_t)py * w + px) * 4;
                dst[0] = dst[1] = dst[2] = dst[3] = 0xFF;
            }
        }
    }
}

