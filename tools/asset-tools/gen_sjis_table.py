#!/usr/bin/env python3
"""
gen_sjis_table.py — re-homed from webgpu-mvp/tools (Phase 5 deletes that tree).

Why it moved: src/assets/sjis_table.h is a generated header that the
product still ships, and this is its only generator. Deleting the prototype would
have left the table unregenerable, so the tool now lives with the other asset tools.

Run it against the product's header path to keep the vendored copy in step:

    python3 tools/asset-tools/gen_sjis_table.py --full \
        -o src/assets/sjis_table.h

Original docstring follows.

gen_sjis_table.py — generate sjis_table.h, the CP932 -> UTF-8 mapping the loader needs.

Why this exists: a `.X` material stores its texture filename as raw Shift-JIS bytes
("服.bmp"), while file and bundle entry names are UTF-8. Resolving one against the
other needs a conversion, and shipping all ~9800 CP932 mappings would be mostly dead
weight in a header. So this emits only the sequences the shipped assets actually use,
plus the full ASCII/half-width range.

    python3 tools/gen_sjis_table.py <asset-root> [-o sjis_table.h]
    python3 tools/gen_sjis_table.py --full          # every CP932 mapping (~50 KB)

Re-run it when new assets introduce characters the table lacks — the runtime reports
every unresolved name, so a miss is visible rather than silent.
"""
import argparse
import glob
import os
import re
import sys

TEX_RE = re.compile(rb'TextureFilename\s*\{\s*"((?:[^"\\]|\\.)*)"', re.S)


def is_lead(b):
    return 0x81 <= b <= 0x9F or 0xE0 <= b <= 0xFC


def sequences_in(raw):
    """Split raw CP932 bytes into single/double byte sequences, skipping ASCII."""
    out, i = [], 0
    while i < len(raw):
        b = raw[i]
        if b < 0x80:
            i += 1
            continue
        if is_lead(b) and i + 1 < len(raw):
            out.append(raw[i:i + 2])
            i += 2
        else:
            out.append(raw[i:i + 1])
            i += 1
    return out


def scan_assets(root):
    """Collect the CP932 sequences used by every TextureFilename in the tree."""
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
    import x2txt  # noqa: E402  (local reference converter)

    seqs = set()
    files = sorted(glob.glob(os.path.join(root, '**', '*.x'), recursive=True) +
                   glob.glob(os.path.join(root, '**', '*.X'), recursive=True))
    for f in files:
        try:
            text, _ = x2txt.convert(f)
        except Exception:
            continue
        for m in TEX_RE.finditer(text):
            for s in sequences_in(m.group(1).replace(b'\\\\', b'\\')):
                seqs.add(s)
    return seqs, len(files)


def full_set():
    """Every CP932 mapping that decodes to a character, via Python's codec."""
    seqs = set()
    for b in range(0x80, 0x100):
        try:
            bytes([b]).decode('cp932')
            if b >= 0x80:
                seqs.add(bytes([b]))
        except Exception:
            pass
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
        for trail in range(0x40, 0xFD):
            try:
                seqs.add(bytes([lead, trail]).decode('cp932').encode('cp932'))
            except Exception:
                pass
    return seqs


def emit(seqs, out_path, full=False):
    entries = []
    for s in seqs:
        try:
            u = s.decode('cp932')
        except Exception:
            continue
        utf8 = u.encode('utf-8')
        if len(utf8) > 4:
            continue
        if len(s) == 1:
            code = s[0]
        elif len(s) == 2:
            code = (s[0] << 8) | s[1]
        else:
            continue
        entries.append((code, utf8))
    entries.sort()

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('// sjis_table.h — CP932 -> UTF-8 table, GENERATED by '
                'tools/gen_sjis_table.py.\n')
        f.write('// Do not edit by hand; re-run the generator to extend it.\n')
        f.write('//\n')
        if full:
            f.write('// %d entries: the full CP932 set, so every Shift-JIS sequence\n'
                    % len(entries))
            f.write('// converts, not only the ones the shipped .X texture filenames use.\n')
            f.write('// Menu and message text needs the wide table — those strings come\n')
            f.write('// from the bundles, and the narrow scan never saw them.\n')
        else:
            f.write('// %d entries. Covers the characters the shipped assets use in\n'
                    % len(entries))
            f.write('// .X texture filenames; a `.X` stores them as raw Shift-JIS while file\n')
            f.write('// and bundle names are UTF-8, so a lookup needs this conversion.\n')
            f.write('//\n')
            f.write('// Re-run with --full when text outside texture names must convert too.\n')
        f.write('#pragma once\n\n#include <cstdint>\n\nnamespace xm {\nnamespace detail {\n\n')
        f.write('struct SjisEntry { uint16_t code; uint8_t len; uint8_t utf8[4]; };\n\n')
        f.write('inline constexpr SjisEntry kSjisTable[] = {\n')
        for code, utf8 in entries:
            pad = utf8 + b'\x00' * (4 - len(utf8))
            lit = ', '.join('0x%02x' % c for c in pad)
            f.write('    {0x%04X, %d, {%s}},\n' % (code, len(utf8), lit))
        f.write('};\n\n')
        f.write('inline constexpr int kSjisTableSize = '
                'sizeof(kSjisTable) / sizeof(kSjisTable[0]);\n\n')
        f.write('}  // namespace detail\n}  // namespace xm\n')
    return len(entries)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('root', nargs='?', help='asset root to scan for texture references')
    ap.add_argument('-o', '--out', default='sjis_table.h')
    ap.add_argument('--full', action='store_true',
                    help='emit every CP932 mapping instead of just the used ones')
    args = ap.parse_args()

    if args.full:
        seqs = full_set()
        print('full CP932 set: %d sequences' % len(seqs))
    else:
        if not args.root:
            ap.error('give an asset root, or use --full')
        seqs, n = scan_assets(args.root)
        print('scanned %d .x files, found %d distinct CP932 sequences' % (n, len(seqs)))

    n = emit(seqs, args.out, args.full)
    print('wrote %s (%d entries, %d bytes)' % (args.out, n, os.path.getsize(args.out)))


if __name__ == '__main__':
    main()
